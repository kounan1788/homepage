// 月の最初の土曜日の日付(1始まり)を返す（範囲外フォールバック用）
export function getFirstSaturdayOfMonth(year: number, month: number): number {
    const firstDayOfWeek = new Date(year, month, 1).getDay();
    return 1 + ((6 - firstDayOfWeek + 7) % 7);
}

// 定休日判定: 2026年度は画像どおりの休日セット、範囲外は日曜・祝日・第2/第4土曜で代替
export function isClosedDay(year: number, month: number, day: number): boolean {
    const dateStr = `${year}-${String(month + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;

    if (dateStr >= '2026-04-01' && dateStr <= '2027-03-31') {
        return CLOSED_DATES.has(dateStr);
    }

    const dow = new Date(year, month, day).getDay();
    if (dow === 0) return true;
    if (JAPANESE_HOLIDAYS[dateStr]) return true;
    if (dow === 6) {
        const firstSat = getFirstSaturdayOfMonth(year, month);
        const satNum = Math.floor((day - firstSat) / 7) + 1;
        return satNum === 2 || satNum === 4;
    }
    return false;
}

/** 営業時間の表記。ヘッダー・フッターの記載と揃えること */
export const OPENING_HOURS = { weekday: '9:00〜18:00', saturday: '9:00〜17:00' } as const;

/**
 * 今日の営業状態。チャットボットのヘッダーに出す。
 * サーバーとブラウザで日付がずれてちらつかないよう、マウント後に呼ぶこと。
 */
export function getTodayStatus(now = new Date()): { open: boolean; label: string } {
    const closed = isClosedDay(now.getFullYear(), now.getMonth(), now.getDate());
    if (closed) return { open: false, label: '本日は定休日' };

    const hours = now.getDay() === 6 ? OPENING_HOURS.saturday : OPENING_HOURS.weekday;
    return { open: true, label: `本日 ${hours}` };
}
