/**
 * 各サービスの「よくあるご質問」を一元管理するファイル。
 *
 * 各ページのFAQ表示・FAQPage構造化データ・チャットボット（components/ServiceChat.tsx）が
 * すべてここを読む。ページ側に書き写すと料金改定や制度変更のときに片方だけ古くなるため、
 * 文面を変えるときは必ずこのファイルだけを編集すること。
 *
 * 各項目はキー付きで持つ。ページ側は Object.values() で表示順に並べ、
 * チャットボットは topFaq.hours のようにキーで1件だけ引く。
 * キーを消すとチャット側がビルドで落ちるため、文面の差し替えはキーを変えずに行うこと。
 *
 * 金額は lib/carPrices.ts を単一の情報源とし、手書きしない。
 */

import { ANNUAL_INTEREST_RATE, carBasePrices } from './carPrices';
import { sortedCarLineup, type CarCategory } from './carLineup';

export interface FaqItem {
    question: string;
    answer: string;
}

/** 実質年率の表示用（3.9%） */
const RATE_LABEL = `${(ANNUAL_INTEREST_RATE * 100).toFixed(1)}%`;

/** カテゴリで最も安い月額（例: '41,000'）。料金データから出すので表記が食い違わない */
const lowestMonthly = (category: CarCategory): string =>
    carBasePrices[sortedCarLineup[category][0].route].toLocaleString();

